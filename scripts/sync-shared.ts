// Copies shared/*.ts(x) into plugins/<p>/hooks/_shared/ with a GENERATED header.
// Run: node scripts/sync-shared.ts [--check]   (--check writes nothing, exits 1 on drift)
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, unlinkSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

// Only these plugins receive the shared kit. Missing folders are skipped. agent-pets is legacy: never listed.
const PLUGINS = ['safety', 'usage', 'awareness', 'agents', 'dev', 'compact']

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = join(root, 'shared')
const check = process.argv.includes('--check')
const HEADER = (f: string): string => `// GENERATED by scripts/sync-shared.ts from shared/${f}. Edit shared/, not this copy.\n`

const files = readdirSync(src).filter(f => /\.(ts|tsx)$/.test(f))
let drift = 0
let synced = 0
for (const p of PLUGINS) {
  const pdir = join(root, 'plugins', p)
  if (!existsSync(pdir)) { console.log(`skip ${p} (no folder yet)`); continue }
  const dest = join(pdir, 'hooks', '_shared')
  if (!check) mkdirSync(dest, { recursive: true })
  for (const f of files) {
    const want = HEADER(f) + readFileSync(join(src, f), 'utf8')
    const path = join(dest, f)
    const have = existsSync(path) ? readFileSync(path, 'utf8') : undefined
    if (have === want) continue
    drift++
    if (check) console.log(`drift: plugins/${p}/hooks/_shared/${f}`)
    else writeFileSync(path, want)
  }
  if (existsSync(dest)) {
    for (const f of readdirSync(dest)) {
      if (files.includes(f)) continue
      if (!readFileSync(join(dest, f), 'utf8').startsWith('// GENERATED by scripts/sync-shared.ts')) continue
      drift++
      if (check) console.log(`stale: plugins/${p}/hooks/_shared/${f}`)
      else unlinkSync(join(dest, f))
    }
  }
  synced++
}
console.log(check ? (drift ? `${drift} drifted` : `clean (${synced} plugins)`) : `synced ${synced} plugins, ${drift} files changed`)
process.exit(check && drift ? 1 : 0)

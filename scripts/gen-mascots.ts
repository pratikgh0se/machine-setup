// Writes shared/mascots.ts: base64 of the two mascot stills. Run: node scripts/gen-mascots.ts
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const assets = join(root, 'research/brainstorm/assets')
const b64 = (f: string): string => readFileSync(join(assets, f)).toString('base64')

const out = `// GENERATED by scripts/gen-mascots.ts from research/brainstorm/assets/*.png. Do not edit.
// 160x160 PNG stills, base64 (no data: prefix). Use mascotSvg() from svgkit.ts to draw them.
export const POM_IDLE = '${b64('pom-idle.png')}'
export const CARROT_IDLE = '${b64('carrot-idle.png')}'
`
writeFileSync(join(root, 'shared/mascots.ts'), out)
console.log('wrote shared/mascots.ts', out.length, 'chars')
